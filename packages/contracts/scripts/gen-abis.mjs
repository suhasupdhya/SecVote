// Copies ABIs (from forge `out/`) and deployment addresses into packages/shared.
// Nobody copies ABI JSON by hand.  Run after `forge build` and after each deploy.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, "..")
const shared = join(root, "..", "shared")
const contracts = { Election: "Election.sol", ElectionFactory: "ElectionFactory.sol" }

mkdirSync(join(shared, "abi"), { recursive: true })
mkdirSync(join(shared, "src"), { recursive: true })

let ts = "// AUTO-GENERATED by packages/contracts/scripts/gen-abis.mjs — do not edit.\n"
for (const [name, file] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(join(root, "out", file, `${name}.json`), "utf8"))
  writeFileSync(join(shared, "abi", `${name}.json`), JSON.stringify(abi, null, 2) + "\n")
  ts += `export const ${name[0].toLowerCase() + name.slice(1)}Abi = ${JSON.stringify(abi)} as const\n`
}

const deployments = {}
const dir = join(root, "deployments")
if (existsSync(dir)) {
  for (const f of readdirSync(dir).filter((f) => f.endsWith(".json"))) {
    deployments[f.replace(".json", "")] = JSON.parse(readFileSync(join(dir, f), "utf8"))
  }
}
writeFileSync(join(shared, "deployments.json"), JSON.stringify(deployments, null, 2) + "\n")
ts += `export const deployments = ${JSON.stringify(deployments)} as const\n`
writeFileSync(join(shared, "src", "contracts.ts"), ts)
console.log("wrote ABIs for", Object.keys(contracts).join(", "), "and", Object.keys(deployments).length, "deployment(s)")
